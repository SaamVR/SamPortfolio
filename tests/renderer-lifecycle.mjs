import {browserConfig} from './browser-config.mjs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const {baseUrl,launchOptions}=browserConfig();
const browser=await chromium.launch(launchOptions);
const checks=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 await page.goto(baseUrl);await page.waitForSelector('#renderer[data-ready=true]');
 const normal=await page.locator('#renderer').evaluate(h=>({attributes:h.querySelector('canvas').getContext('webgl2').getContextAttributes(),frames:h.dataset.frames,bounds:h.dataset.bounds,adapter:!!h.__openingStage}));
 assert.equal(normal.attributes.preserveDrawingBuffer,false,'production must not retain capture framebuffer');
 assert.equal(normal.frames,undefined);assert.equal(normal.bounds,undefined);assert.equal(normal.adapter,false);
 const canvas=await page.locator('#renderer').screenshot({path:'evidence/normal-canvas.png'});
 // A real pixel check compares rendered canvas with an empty same-sized element.
 await page.locator('canvas').evaluate(c=>c.style.visibility='hidden');
 const empty=await page.locator('#renderer').screenshot();
 await page.locator('canvas').evaluate(c=>c.style.visibility='');
 assert.notDeepEqual(canvas,empty,'normal framebuffer screenshot must contain rendered geometry');
 checks.push('normal mode: non-retained buffer, no heavy diagnostics or adapter; rendered canvas differs from empty host');
 await page.locator('button[data-feel=playful]').click();
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'));});
 assert.equal(await page.locator('#renderer').getAttribute('data-active'),'false');
 await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
 await page.evaluate(()=>scrollTo(0,2000));await page.waitForTimeout(100);
 await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(150);
 assert.equal(await page.locator('#renderer').getAttribute('data-angles'),'[-28,34,14]');
 await page.locator('button[data-feel=cinematic]').click();
 await page.locator('#mode-toggle').click();assert.equal(await page.locator('canvas').count(),0);
 await page.locator('#mode-toggle').click();await page.waitForSelector('#renderer[data-ready=true]');
 assert.equal(await page.locator('#renderer').getAttribute('data-angles'),'[-38,42,18]');
 const idle=await page.locator('#renderer').getAttribute('data-frame-count');await page.waitForTimeout(150);assert.equal(await page.locator('#renderer').getAttribute('data-frame-count'),idle);
 await page.setViewportSize({width:1200,height:900});await page.waitForTimeout(100);assert.equal(await page.locator('#renderer').getAttribute('data-angles'),'[-38,42,18]');
 checks.push('simulated hidden-document event settles latest choice; native scroll reentry, resize and idle frame count preserved');
 checks.push('active Light switch disposes scene; Full reentry settles current choice');
 await context.close();
 const diagnostic=await browser.newContext({viewport:{width:1440,height:1000}});const dp=await diagnostic.newPage();await dp.goto(baseUrl+'/?openingDiagnostics=1');await dp.waitForSelector('#renderer[data-ready=true]');
 const trace=await dp.locator('#renderer').evaluate(h=>({retained:h.querySelector('canvas').getContext('webgl2').getContextAttributes().preserveDrawingBuffer,adapter:!!h.__openingStage,frames:!!h.dataset.frames,bounds:!!h.dataset.bounds}));
 assert.deepEqual(trace,{retained:false,adapter:false,frames:true,bounds:true});checks.push('diagnostics-only tracing leaves capture retention and PNG adapter disabled');await diagnostic.close();
 const delayed=await browser.newContext({viewport:{width:1440,height:1000}});
 let release;const gate=new Promise(r=>release=r);let requested;const arrived=new Promise(r=>requested=r);
 await delayed.route('**/*renderer*.js',async route=>{requested();await gate;await route.continue();});
 const slow=await delayed.newPage();await slow.goto(baseUrl);await arrived;
 await slow.locator('#mode-toggle').click();release();await slow.waitForLoadState('networkidle');
 assert.equal(await slow.locator('canvas').count(),0);
 assert.equal(await slow.locator('#poster-image').evaluate(i=>getComputedStyle(i).visibility),'visible');
 checks.push('Light chosen during dynamic import never revives stale renderer');await delayed.close();
 const capture=await browser.newContext({viewport:{width:1440,height:1000}});
 const cp=await capture.newPage();await cp.goto(baseUrl+'/?openingCapture=1');await cp.waitForSelector('#renderer[data-ready=true]');
 const captured=await cp.locator('#renderer').evaluate(h=>({png:h.__openingStage.capturePng(),retained:h.querySelector('canvas').getContext('webgl2').getContextAttributes().preserveDrawingBuffer,frames:!!h.dataset.frames,bounds:!!h.dataset.bounds}));
 assert.equal(captured.retained,true);assert.equal(captured.frames,true);assert.equal(captured.bounds,true);
 assert.ok(captured.png.startsWith('data:image/png;base64,'));assert.ok(captured.png.length>10000);
 const buffer=Buffer.from(captured.png.split(',')[1],'base64');assert.equal(buffer.readUInt32BE(16),await cp.locator('canvas').evaluate(c=>c.width));
 await writeFile('evidence/capture-adapter.png',buffer);
 await cp.locator('#renderer').evaluate(h=>window.__disposedCapture=h.__openingStage);
 await cp.locator('#mode-toggle').click();assert.equal(await cp.locator('#renderer').evaluate(h=>!!h.__openingStage),false);
 assert.equal(await cp.evaluate(()=>{try{window.__disposedCapture.capturePng();return false;}catch(e){return e.message==='Stage is disposed.';}}),true);
 checks.push('explicit capture renders/reads synchronously and removes diagnostic adapter on disposal');await capture.close();
 await writeFile('evidence/renderer-lifecycle.json',JSON.stringify({runAt:new Date().toISOString(),browser:browser.version(),environment:'Headless Chromium / SwiftShader; capture mode explicitly enabled only in final profile',checks},null,2));
 console.log('PASS: renderer lifecycle and production/capture separation.');
}finally{await browser.close();}
